"""Build recode/reports/00_inventory.md from the canonical corpus (BRIEF section 1.4).

Reads recode/data/canonical/edits.jsonl (built by build_phase0.py) plus the
three non-reliable raw run files (inventory-flag only; never canonicalized),
recomputes every count from the data, and writes the Phase 0 inventory report.

Per the audit corrections:
  - per-model match-strategy rows are computed EXCLUDING error records (whose
    stored "exact" is a meaningless publish-time default) — repo_map section 4.5's
    per-model rows mixed the defaults in;
  - the non-reliable fragment run_20260501_193324 also contains 1 duplicate
    (model, doc, cond, round) tuple, so the pilot is not the only file with
    duplicates.

    .venv/bin/python recode/src/build_inventory.py
"""

from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import (  # noqa: E402
    CANONICAL_DIR,
    NON_RELIABLE_RUN_STEMS,
    REPORTS_DIR,
    load_run_records,
)

EDITS_PATH = CANONICAL_DIR / "edits.jsonl"
OUT_PATH = REPORTS_DIR / "00_inventory.md"

CONDITION_ORDER = [
    "allow_no_edit", "baseline", "cross_edit",
    "implementation_note", "no_constitution_prepend", "you_framing",
]
MODEL_ORDER = [
    "Claude Haiku 4.5", "Claude Opus 4.7", "Claude Sonnet 4.6",
    "GPT-5.4", "GPT-5.4 Mini", "GPT-5.5",
    "Gemini 3 Flash", "Gemini 3.1 Pro", "Grok 4.2", "Grok 4.3",
]


def load_edits() -> list[dict]:
    records = []
    with open(EDITS_PATH, encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                records.append(json.loads(line))
    return records


def md_table(headers: list[str], rows: list[list]) -> list[str]:
    lines = ["| " + " | ".join(str(h) for h in headers) + " |"]
    lines.append("|" + "---|" * len(headers))
    for row in rows:
        lines.append("| " + " | ".join(str(c) for c in row) + " |")
    return lines


def main() -> None:
    edits = load_edits()
    n = len(edits)
    chains = sorted({(r["run_id"], r["model_id"], r["document_id"], r["condition"]) for r in edits})

    # -- core aggregations, all recomputed from edits.jsonl --------------------
    by_model_cond: dict[tuple, int] = Counter()
    by_model: dict[str, list[dict]] = defaultdict(list)
    by_file: dict[str, list[dict]] = defaultdict(list)
    by_doc: dict[str, list[dict]] = defaultdict(list)
    for r in edits:
        by_model_cond[(r["model"], r["condition"])] += 1
        by_model[r["model"]].append(r)
        by_file[r["run_id"]].append(r)
        by_doc[r["document_id"]].append(r)

    def status(rs, s):
        return sum(1 for r in rs if r["apply_status"] == s)

    n_applied = status(edits, "applied")
    n_abst = status(edits, "no_change")
    n_err = sum(1 for r in edits if r["error"])
    n_v1 = sum(1 for r in edits if r["v1_code"] is not None)
    strategies = Counter(r["match_strategy"] for r in edits if r["apply_status"] == "applied")
    fragments = [r for r in edits if r["total_rounds_metadata"] == 3]
    fragment_chains = {(r["run_id"], r["model_id"], r["document_id"], r["condition"]) for r in fragments}

    # -- chain integrity checks ------------------------------------------------
    rounds_by_chain: dict[tuple, list[int]] = defaultdict(list)
    for r in edits:
        rounds_by_chain[(r["run_id"], r["model_id"], r["document_id"], r["condition"])].append(r["round"])
    bad_chains = {k: v for k, v in rounds_by_chain.items() if sorted(v) != list(range(1, 21))}
    assert not bad_chains, f"chains without exactly rounds 1..20: {list(bad_chains)[:3]}"
    assert len(chains) == 137, f"expected 137 chains, got {len(chains)}"

    # -- non-reliable files (raw, flag-only) -----------------------------------
    nonrel_rows = []
    for stem in NON_RELIABLE_RUN_STEMS:
        raw = load_run_records(stem)
        errs = sum(1 for r in raw if r.get("error"))
        tr = Counter(int(r["total_rounds"]) for r in raw)
        tuples = Counter(
            (r["model_id"], r["document_id"], r.get("condition_id", "baseline"), int(r["round_number"]))
            for r in raw
        )
        dups = sum(v - 1 for v in tuples.values() if v > 1)
        nonrel_rows.append([
            stem, len(raw), errs,
            ", ".join(f"{k}: {v}" for k, v in sorted(tr.items())), dups,
        ])

    # -- report ----------------------------------------------------------------
    L: list[str] = []
    L += [
        "# Phase 0 inventory — canonical corpus census",
        "",
        "Generated by `recode/src/build_inventory.py` from",
        "`recode/data/canonical/edits.jsonl`; every number below is recomputed",
        "from the canonical records (non-reliable-file rows from the raw files).",
        "",
        "## Headline counts",
        "",
        f"- **Canonical records: {n:,}** — every record in the 7 `RELIABLE_RUNS`",
        f"  files; **{len(chains)} chains**, each exactly rounds 1..20 (verified).",
        f"- Applied edits: **{n_applied:,}**; abstentions: **{n_abst}**; "
        f"generation/apply errors: **{n_err}**.",
        f"- v1-coded records: **{n_v1:,}** (join misses: {n - n_v1} = "
        f"{n_err} errors + {n_abst} abstentions, exactly as expected).",
        f"- Unique `edit_id`s: {len({r['edit_id'] for r in edits}):,} (all unique).",
        "- The paper's \"approximately 2,500 edits\" reconciles as the",
        f"  {n_applied:,} applied-and-v1-coded edits within {n:,} canonical",
        "  round records.",
        "",
        "## Records per model × condition",
        "",
    ]
    rows = []
    for m in MODEL_ORDER:
        row = [m] + [by_model_cond.get((m, c), 0) for c in CONDITION_ORDER]
        row.append(sum(row[1:]))
        rows.append(row)
    total_row = ["**TOTAL**"] + [
        sum(by_model_cond.get((m, c), 0) for m in MODEL_ORDER) for c in CONDITION_ORDER
    ]
    total_row.append(sum(total_row[1:]))
    L += md_table(["model"] + CONDITION_ORDER + ["TOTAL"], rows + [total_row])

    L += [
        "",
        "Cells are unbalanced by design: Grok models have a single own document",
        "(20 records per own-doc condition); Claude Sonnet 4.6, GPT-5.4, and",
        "Gemini 3.1 Pro have a doubled baseline (independent chains in both",
        "run_20260429_175345 and run_20260507_212254); Claude Opus 4.7 has 100",
        "cross_edit records (4 anchor documents + the openai_model_spec_no_csam",
        "rerun of its dead full-spec cell). Workstream D must use exact per-model",
        "chain counts, not an assumed balanced design.",
        "",
        "## Per model: totals, abstentions, failures, chains, v1 join",
        "",
    ]
    rows = []
    for m in MODEL_ORDER:
        rs = by_model[m]
        m_chains = len({(r["run_id"], r["document_id"], r["condition"]) for r in rs})
        rows.append([
            m, len(rs), status(rs, "applied"), status(rs, "no_change"),
            status(rs, "find_not_found"), status(rs, "find_ambiguous"),
            status(rs, "generation_error"), m_chains,
            sum(1 for r in rs if r["v1_code"] is not None),
            sum(1 for r in rs if r["retried"]),
        ])
    L += md_table(
        ["model", "records", "applied", "abstentions", "find_not_found",
         "find_ambiguous", "generation_error", "chains", "v1_coded", "retried"],
        rows,
    )

    L += ["", "## Records per run file", ""]
    rows = []
    for stem in sorted(by_file):
        rs = by_file[stem]
        rows.append([
            stem, len(rs), len({(r["model_id"], r["document_id"], r["condition"]) for r in rs}),
            sum(1 for r in rs if r["error"]), status(rs, "no_change"),
            sum(1 for r in rs if r["v1_code"] is not None),
        ])
    L += md_table(["run file", "records", "chains", "errors", "abstentions", "v1_coded"], rows)

    L += ["", "## Documents", ""]
    rows = []
    for doc in sorted(by_doc):
        rs = by_doc[doc]
        rows.append([
            doc, rs[0]["document_provider"], rs[0]["document_type"],
            rs[0]["document_owner"], len(rs),
        ])
    L += md_table(["document_id", "provider", "doc_type", "owner", "records"], rows)
    L += [
        "",
        "`openai_model_spec_no_csam` is the 8th document id: the initial state of",
        "one 20-round Claude Opus 4.7 cross-edit chain (run_20260518_171402),",
        "re-run after the parallel full-spec chain failed 20/20 (all RetryError).",
        "Its processed source was never committed; it was re-derived and",
        "replay-validated 20/20 — see",
        "`recode/data/derived/openai_model_spec_no_csam_derivation.md`.",
        "Do not double-count the Opus × OpenAI-spec cross cell: the full-spec",
        "chain is 20/20 errors and contributes no applied edits.",
        "",
        "## Match strategies (applied edits only)",
        "",
        f"Corpus-level: exact {strategies['exact']:,}, whitespace "
        f"{strategies['whitespace']}, fuzzy {strategies['fuzzy']} "
        f"(+ {n_abst} no_change abstention records).",
        "",
        "Error records store `match_strategy: \"exact\"` as a publish-time",
        "Pydantic default with no meaning; canonical records null it out and the",
        "table below EXCLUDES error records (note: naive per-model counts that",
        "include the defaults — e.g. repo_map section 4.5's rows — overstate",
        "'exact' for every model with errors).",
        "",
    ]
    rows = []
    for m in MODEL_ORDER:
        st = Counter(r["match_strategy"] for r in by_model[m] if r["apply_status"] == "applied")
        rows.append([m, st.get("exact", 0), st.get("whitespace", 0), st.get("fuzzy", 0),
                     status(by_model[m], "no_change")])
    L += md_table(["model", "exact", "whitespace", "fuzzy", "no_change"], rows)

    heading_rows = []
    for doc in sorted(by_doc):
        applied = [r for r in by_doc[doc] if r["apply_status"] == "applied"]
        n_with = sum(1 for r in applied if r["section_heading"])
        n_empty = len(applied) - n_with
        examples = sorted({r["section_heading"] for r in applied if r["section_heading"]})
        heading_rows.append([
            doc, len(applied), n_with, n_empty,
            "; ".join(examples[:3]) + ("; …" if len(examples) > 3 else ""),
        ])
    heading_table = md_table(
        ["document_id", "applied", "with heading", "empty (no heading above span)",
         "example headings"],
        heading_rows,
    )

    err_class = Counter(r["apply_status"] for r in edits if r["error"])
    L += [
        "",
        "## apply_status (extended enum)",
        "",
        "The brief's enum {applied, find_not_found, find_ambiguous} required two",
        "extensions, documented here per the schema:",
        "",
        "- `no_change` — the 2 abstentions (both Grok 4.3, grok_system_prompt,",
        "  allow_no_edit, rounds 18 and 20, run_20260507_212254; literal",
        "  `[NO CHANGE]` in both fields). v1 never coded them; v2 must.",
        "- `generation_error` — API/parse failures with no edit text (RetryError,",
        "  missing delimiters, truncated responses, NoneType): the model never",
        "  produced an applicable FIND/REPLACE, so neither brief category fits.",
        "",
        f"Error-record split: find_not_found {err_class.get('find_not_found', 0)},",
        f"find_ambiguous {err_class.get('find_ambiguous', 0)},",
        f"generation_error {err_class.get('generation_error', 0)}",
        f"(total {n_err}). Error records never advance document state, occupy",
        "their round slot permanently (never re-attempted in reliable runs), and",
        "carry empty find/replace text; they are canonicalized (round-index",
        "integrity, F3 apply-failure reporting) but excluded from grading and",
        "from match-strategy statistics.",
        "",
        "## Correction: `total_rounds: 3` records are NOT duplicates (DECISIONS section 6)",
        "",
        f"{len(fragments)} records in reliable files carry `total_rounds: 3`",
        f"({len(fragment_chains)} chains: 84 in run_20260507 + 48 in run_20260513 +",
        "6 in run_20260516). These are rounds 1–3 of chains whose rounds 4–20",
        "were appended later by a resumed invocation stamping `total_rounds: 20`.",
        "Verified: rounds are disjoint, zero duplicate (run file, model, doc,",
        "condition, round) tuples exist in any reliable file, and every chain has",
        "exactly rounds 1..20. DECISIONS section 6's original wording (\"dedup",
        "resume fragments\") is corrected: ALL 2,740 records are kept; dropping",
        "the fragments would amputate rounds 1–3 of 46 chains and break replay of",
        "rounds 4–20. `total_rounds` is retained only as",
        "`total_rounds_metadata` and must never be used for chain length.",
        "",
        "Chain identity includes the run file: six capable-baseline (model, doc)",
        "cells were legitimately run twice (run_20260429 + run_20260507) and would",
        "collide on 120 (model, doc, condition, round) tuples without it.",
        "",
        "## Replay verification",
        "",
        "All 137 chains replay end-to-end from the pristine processed documents",
        f"(`data/processed/`, regenerated; no_csam from the derived file): all",
        f"{n_applied:,} applied edits matched with `match_count == 1` AND",
        "reproduced the recorded `match_strategy` (exact/whitespace/fuzzy) —",
        "the generation-time `ensure_unique_match` oracle. Context fields",
        "(`section_heading`, `context_before`, `context_after`) come from the",
        "pre-application state of each round. Convention: paragraphs are maximal",
        "blank-line-separated blocks; for a span starting in paragraph i and",
        "ending in paragraph j, context_before = paragraph i−1 ('' at document",
        "start), context_after = paragraph j+1 ('' at document end),",
        "section_heading = nearest heading line at or above the span's first",
        "line under the document's heading style(s) — see below (a span",
        "starting at a heading line returns that heading; a span covering",
        "several sections is attributed to the section where it starts).",
        "No pure additions exist (0 empty FINDs among applied edits; 4 empty",
        "REPLACEs are pure deletions). Whitespace/fuzzy spans run token-start to",
        "token-end (surrounding whitespace survives), which the context extractor",
        "handles by paragraph offsets, not span-string equality.",
        "",
        "### Section-heading detection is per document",
        "",
        "Three processed documents contain ZERO ATX '#' headings — their real",
        "headings use other styles — so a '#'-only extractor would leave",
        "section_heading empty on every one of their applied records",
        "(claude_constitution, opus_system_prompt, gemini_system_prompt: ~47% of",
        "the applied corpus). `recode/src/replay.py` therefore detects, per",
        "document (ATX headings outside fenced code blocks are recognized",
        "everywhere, covering headings models themselves introduce):",
        "",
        "- **claude_constitution, gpt_system_prompt** — standalone bare-line",
        "  headings: blank lines on both sides, ≤ 80 chars, letters but no",
        "  digits, no sentence-final punctuation, no list/markup/code characters",
        "  (e.g. \"Being broadly safe\", \"Preface\", \"Environment\").",
        "- **opus_system_prompt** — pseudo-XML bracket tags (`[memory_system]` →",
        "  heading `memory_system`); `[/tag]` closes a section and the upward",
        "  scan is nesting-aware, so a span below a closed sibling section",
        "  resolves to its true enclosing tag, while a closing tag at or below",
        "  the span's own first line (an edit at a section's tail boundary)",
        "  does not wall off the enclosing section. Plus blank-above bare-line",
        "  headings (this document's headings often lead directly into their",
        "  paragraph, e.g. \"Data Scope\").",
        "- **gemini_system_prompt** — full-line bold headings (≤ 80 chars, not a",
        "  list item), tolerating the document's mangled variants missing one",
        "  `**` delimiter (e.g. `**III. Guardrail**`, `Response Guiding",
        "  Principles**`).",
        "",
        "These are heuristics applied to the evolving replayed state; they were",
        "validated line-by-line against the pristine documents (every real",
        "heading recovered; known noise: the constitution's front-matter line",
        "\"Published\" passes the filter, affecting only spans in the title",
        "block). A record whose section_heading is '' after this sits in a",
        "document preamble above the first heading (the Gemini identity",
        "paragraph, the ChatGPT identity line) or, in a handful of",
        "opus_system_prompt cases, in a mid-run state the editing model had",
        "restructured so that no recognizable heading remains above the span —",
        "a small, genuine set (counts below), rendered as an empty `Section:`",
        "line to the v2 grader.",
        "",
        "Section-heading coverage per document (applied records):",
        "",
        *heading_table,
        "",
        "## Two text versions per edit",
        "",
        "`replace_text` is the raw recorded text that `apply_diff` actually",
        "applied (replay fidelity); `replace_text_sanitized` is",
        "`export_changes.sanitize_replace_text` output — the text the v1 grader",
        "saw — copied verbatim from the v1 coded file's `changed_text` for all",
        f"{n_v1:,} coded records (fallback sanitization applied only to the 2",
        "abstentions). v2 graders receive the sanitized text for v1/v2",
        "comparability.",
        "",
        "## Non-reliable run files (flagged, never canonicalized or coded)",
        "",
    ]
    L += md_table(
        ["run file", "records", "errors", "total_rounds mix", "duplicate (m,d,c,r) tuples"],
        nonrel_rows,
    )
    L += [
        "",
        "- `run_20260320_173238`: mixed 10/20-round pilot with ragged chains and",
        "  19 genuinely duplicated (model, doc, condition, round) tuples (errored",
        "  attempt + later success).",
        "- `run_20260421_225849`: 3-round aborted cross-edit smoke test.",
        "- `run_20260501_193324`: 3-record fragment, all errors — and note it",
        "  also contains 1 duplicate (model, doc, condition, round) tuple, so the",
        "  pilot is not the only non-reliable file with duplicates.",
        "",
        "## Oddities flagged (BRIEF section 1.4)",
        "",
        "- Cells with fewer than 20 applied edits: the dead Claude Opus 4.7 ×",
        "  openai_model_spec × cross_edit chain (0 applied, 20/20 RetryError) and",
        "  every cell diluted by errors — notably GPT-5.4 Mini (94 errors,",
        "  concentrated in run_20260403/run_20260424).",
        "- No runs shorter than 20 rounds exist in the canonical frame; no",
        "  duplicated edits exist in it either (see the correction above).",
        "- `seed` is null on every record: no seed was stored at generation time",
        "  (DECISIONS section 7); chains are identified by run file + (model,",
        "  document, condition).",
        "- Only GPT-5.5 ran with a reasoning parameter at generation time",
        "  (effort=medium, frontier configs); Claude Opus 4.7 deliberately had",
        "  none — a within-tier asymmetry to keep in mind for frontier",
        "  comparisons.",
        f"- retried=true on {sum(1 for r in edits if r['retried'])} records",
        "  (never co-occurs with error).",
        "",
    ]

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT_PATH} ({len(L)} lines)")


if __name__ == "__main__":
    main()
