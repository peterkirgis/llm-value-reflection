"""Re-derive data/processed/openai_model_spec_no_csam.md (DECISIONS section 11).

The processed initial document for the 20-round Claude Opus 4.7 cross-edit
chain on `openai_model_spec_no_csam` (run_20260518_171402) was never committed
and is not generated by src/valconv/documents.py. Per
experiments/iterative_edit/config_frontier_cross_no_csam.yaml, that document is
the OpenAI Model Spec with the "CSAM + info-hazards subsections removed".

This script removes exactly two `####` subsections from
data/processed/openai_model_spec.md, each from its heading line up to (not
including) the next heading of equal or higher level:

  1. "#### Never generate sexual content involving minors"
  2. "#### Don\\'t provide information hazards"   (heading as it appears,
     with the escaped apostrophe, under "### Restricted content")

and writes the result to analysis/data/derived/openai_model_spec_no_csam.md.

VALIDATION (the correctness oracle): the 20-round chain is replayed from the
derived document; every round must apply with match_count == 1 and reproduce
the recorded match_strategy. A per-round validation table is written to
analysis/data/derived/openai_model_spec_no_csam_derivation.md.

    .venv/bin/python analysis/src/derive_no_csam.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import (  # noqa: E402
    DERIVED_DIR,
    DERIVED_DOC_ID,
    DERIVED_DOC_PATH,
    PROCESSED_DIR,
    group_chains,
    load_run_records,
)
from replay import find_span  # noqa: E402
from valconv.diffing import apply_diff  # noqa: E402

RUN_STEM = "run_20260518_171402"

SUBSECTIONS_TO_REMOVE = [
    "#### Never generate sexual content involving minors",
    "#### Don\\'t provide information hazards",
]


def remove_subsection(content: str, heading_line: str) -> str:
    lines = content.split("\n")
    try:
        start = lines.index(heading_line)
    except ValueError:
        raise SystemExit(f"heading not found: {heading_line!r}")
    level = len(heading_line) - len(heading_line.lstrip("#"))
    end = len(lines)
    for i in range(start + 1, len(lines)):
        m = re.match(r"^(#{1,6})\s", lines[i])
        if m and len(m.group(1)) <= level:
            end = i
            break
    return "\n".join(lines[:start] + lines[end:])


def derive() -> str:
    content = (PROCESSED_DIR / "openai_model_spec.md").read_text(encoding="utf-8")
    for heading in SUBSECTIONS_TO_REMOVE:
        content = remove_subsection(content, heading)
    return content


def validate(derived: str) -> list[dict]:
    records = load_run_records(RUN_STEM)
    chains = group_chains(records)
    chain = None
    for key, chain_records in chains.items():
        if key[1] == DERIVED_DOC_ID:
            chain = chain_records
    if chain is None:
        raise SystemExit(f"no {DERIVED_DOC_ID} chain found in {RUN_STEM}")

    rows = []
    state = derived
    for record in chain:
        assert not record.get("error") and not record.get("no_change")
        span = find_span(state, record["find_text"])
        result = apply_diff(state, record["find_text"], record["replace_text"])
        ok = (
            result.match_count == 1
            and result.match_strategy == record["match_strategy"]
            and span.match_strategy == result.match_strategy
        )
        rows.append(
            {
                "round": int(record["round_number"]),
                "recorded_strategy": record["match_strategy"],
                "replay_strategy": result.match_strategy,
                "match_count": result.match_count,
                "find_chars": len(record["find_text"]),
                "ok": ok,
            }
        )
        if not ok:
            raise SystemExit(f"validation FAILED at round {record['round_number']}: {rows[-1]}")
        state = result.new_content
    return rows


def write_notes(rows: list[dict], derived: str, original: str) -> None:
    lines = [
        "# Derivation and validation of openai_model_spec_no_csam.md",
        "",
        "Derived by `analysis/src/derive_no_csam.py` per DECISIONS section 11.",
        "",
        "## Derivation",
        "",
        "Source: `data/processed/openai_model_spec.md` "
        f"({len(original):,} chars). Removed two `####` subsections in full",
        "(heading line through the line before the next heading of equal or",
        "higher level), per the intent stated in",
        "`experiments/iterative_edit/config_frontier_cross_no_csam.yaml`",
        '("CSAM + info-hazards subsections removed"):',
        "",
        "1. `#### Never generate sexual content involving minors` (under `### Prohibited content`)",
        "2. `#### Don\\'t provide information hazards` (under `### Restricted content`; the",
        "   heading carries an escaped apostrophe in the processed source)",
        "",
        f"Result: `analysis/data/derived/openai_model_spec_no_csam.md` ({len(derived):,} chars,",
        f"{len(original) - len(derived):,} chars removed). The file is written under",
        "`analysis/data/derived/`, never into `data/processed/`.",
        "",
        "## Validation (replay oracle)",
        "",
        "The 20-round Claude Opus 4.7 cross-edit chain on this document",
        f"(`{RUN_STEM}.jsonl`) was replayed from the derived file with",
        "`valconv.diffing.apply_diff`. Every round must match exactly once",
        "(`match_count == 1`) and reproduce the recorded `match_strategy`.",
        "",
        "| round | recorded strategy | replay strategy | match_count | FIND chars | ok |",
        "|---|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| {row['round']} | {row['recorded_strategy']} | {row['replay_strategy']} "
            f"| {row['match_count']} | {row['find_chars']} | {'PASS' if row['ok'] else 'FAIL'} |"
        )
    n_ok = sum(1 for r in rows if r["ok"])
    lines += [
        "",
        f"**Result: {n_ok}/{len(rows)} rounds validated.** The chain replays"
        " end-to-end from the derived document, so the derived initial state is"
        " consistent with every recorded FIND span in the chain.",
        "",
        "Caveat: the oracle constrains the derived text only where FIND spans"
        " touch it; text far from every edit is taken on faith from the config's"
        " description. All 20 recorded strategies are `exact`, which makes the"
        " constraint character-exact within each matched span.",
        "",
    ]
    (DERIVED_DIR / "openai_model_spec_no_csam_derivation.md").write_text(
        "\n".join(lines), encoding="utf-8"
    )


def main() -> None:
    original = (PROCESSED_DIR / "openai_model_spec.md").read_text(encoding="utf-8")
    derived = derive()
    rows = validate(derived)
    DERIVED_DIR.mkdir(parents=True, exist_ok=True)
    DERIVED_DOC_PATH.write_text(derived, encoding="utf-8")
    write_notes(rows, derived, original)
    print(f"derived {DERIVED_DOC_PATH} ({len(derived):,} chars)")
    print(f"validated {sum(1 for r in rows if r['ok'])}/{len(rows)} rounds")


if __name__ == "__main__":
    main()
